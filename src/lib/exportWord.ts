function h1(text: string): Paragraph {
  return new Paragraph({
    text,
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 400, after: 200 },
  });
}

function h2(text: string): Paragraph {
  return new Paragraph({
    text,
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 280, after: 120 },
  });
}

function p(text: string, bold = false): Paragraph {
  return new Paragraph({
    children: [new TextRun({ text, bold, size: 24, font: "Times New Roman" })],
    spacing: { after: 120 },
  });
}

function bullet(text: string): Paragraph {
  return new Paragraph({
    children: [new TextRun({ text, size: 24, font: "Times New Roman" })],
    bullet: { level: 0 },
    spacing: { after: 80 },
  });
}

function pageBreak(): Paragraph {
  return new Paragraph({ children: [new PageBreak()] });
}

function cell(text: string, isHeader = false, fill?: string): TableCell {
  return new TableCell({
    children: [
      new Paragraph({
        children: [
          new TextRun({
            text,
            bold: isHeader,
            color: isHeader ? WHITE : "000000",
            size: isHeader ? 20 : 18,
            font: "Times New Roman",
          }),
        ],
        spacing: { before: 40, after: 40 },
      }),
    ],
    shading: {
      fill: fill ?? (isHeader ? NAVY : WHITE),
      type: ShadingType.CLEAR,
      color: "auto",
    },
    margins: { top: 60, bottom: 60, left: 120, right: 120 },
  });
}

function calendarTable(shiftNum: number): Table {
  const data = calendarData.find((s) => s.shiftNum === shiftNum);
  if (!data) return new Table({ rows: [new TableRow({ children: [cell("—")] })] });

  const headerRow = new TableRow({
    children: [
      cell("День", true),
      cell("Дата", true),
      cell("Мероприятие", true),
      cell("Направление", true),
      cell("Ответственный", true),
    ],
    tableHeader: true,
  });

  const rows = data.events.map((ev, idx) => {
    const typeInfo = eventTypeLabels[ev.type as keyof typeof eventTypeLabels];
    const rowFill = idx % 2 === 0 ? WHITE : LIGHT;
    const dirFill =
      ev.type === "russia" ? RED : ev.type === "chelovek" ? BLUE : GREEN;
    const dirLabel =
      ev.type === "russia"
        ? "Россия"
        : ev.type === "chelovek"
        ? "Человек"
        : "Мир";
    return new TableRow({
      children: [
        cell(String(ev.day), false, rowFill),
        cell(ev.date, false, rowFill),
        cell(ev.event, false, rowFill),
        cell(typeInfo?.label ?? dirLabel, false, dirFill),
        cell(ev.responsible, false, rowFill),
      ],
    });
  });

  return new Table({
    layout: TableLayoutType.FIXED,
    width: { size: 100, type: WidthType.PERCENTAGE },
    columnWidths: [700, 800, 4600, 1500, 2400],
    rows: [headerRow, ...rows],
  });
}

